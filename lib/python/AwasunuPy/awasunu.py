## Grammar
def ne(first_noun, second_noun):
  non = "Ne " + first_noun + " ou " + second_noun + ", "

  return non

def mais(third_noun):
  maisette = "mais c'est " + third_noun + "."

  return maisette

def cette(noun, adjective):
  this_noun = noun
  this_adjective = adjective

  phrase = "Cette " + this_noun + " est " + adjective + ", "

  return phrase

def maisette(noun, adjective):
  phrase = "Maisette " + noun + " est " + adjective + "."

  return phrase

def sinon(noun, adj1, adj2, adj3):
  phrase = "Sinon " + noun + " n'est " + adj1 + " ou " + adj2 + " mais c'est " + adj3 + "."

  return phrase

